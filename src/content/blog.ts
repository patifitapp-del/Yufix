export const postBySlug = (s: string) => POSTS.find((p) => p.slug === s);
export const fmtDate = (iso: string) => {
  const m = ['Ocak', 'Şubat', 'Mart', 'Nisan', 'Mayıs', 'Haziran', 'Temmuz', 'Ağustos', 'Eylül', 'Ekim', 'Kasım', 'Aralık'];
  const [y, mo, d] = iso.split('-').map(Number);
  return `${d} ${m[mo - 1]} ${y}`;
};
export const readMin = (p: Post) => {
  const w = p.body.reduce((n, b) => n + (Array.isArray(b.x) ? b.x.join(' ') : b.x).split(/\s+/).length, 0);
  return Math.max(2, Math.round(w / 150));
};
